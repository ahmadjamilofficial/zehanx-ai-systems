create table if not exists public.idea_studio_leads (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  whatsapp text,
  brief jsonb not null,
  transcript jsonb not null default '[]'::jsonb,
  consent boolean not null check (consent = true),
  created_at timestamptz not null default now()
);
alter table public.idea_studio_leads enable row level security;
-- No public policies. Server-side inserts use the service-role key only.
